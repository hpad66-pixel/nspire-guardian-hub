CREATE INDEX IF NOT EXISTS project_conditions_project_class_idx
  ON public.project_condition_records(project_id, classification, classification_status);
CREATE INDEX IF NOT EXISTS project_conditions_field_item_idx
  ON public.project_condition_records(field_item_id) WHERE field_item_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS project_condition_comments_condition_idx
  ON public.project_condition_comments(condition_id, created_at);
CREATE INDEX IF NOT EXISTS project_condition_notations_condition_idx
  ON public.project_condition_notations(condition_id, created_at);
CREATE INDEX IF NOT EXISTS project_condition_photos_condition_idx
  ON public.project_condition_photos(condition_id, sort_order);
