CREATE OR REPLACE FUNCTION public.log_project_condition_change()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO public.project_condition_audit_events(tenant_id, project_id, condition_id, event_type, actor_id, note)
    VALUES (NEW.tenant_id, NEW.project_id, NEW.id, 'condition.created', NEW.created_by, 'Project condition created');
  ELSIF NEW.status IS DISTINCT FROM OLD.status THEN
    INSERT INTO public.project_condition_audit_events(tenant_id, project_id, condition_id, event_type, actor_id, note, metadata)
    VALUES (
      NEW.tenant_id,
      NEW.project_id,
      NEW.id,
      'condition.status_changed',
      auth.uid(),
      'Project condition status changed',
      jsonb_build_object('from_status', OLD.status, 'to_status', NEW.status)
    );
  ELSIF NEW.client_publish_status IS DISTINCT FROM OLD.client_publish_status THEN
    INSERT INTO public.project_condition_audit_events(tenant_id, project_id, condition_id, event_type, actor_id, note, metadata)
    VALUES (
      NEW.tenant_id,
      NEW.project_id,
      NEW.id,
      'condition.publish_status_changed',
      auth.uid(),
      'Project condition publish status changed',
      jsonb_build_object('from_status', OLD.client_publish_status, 'to_status', NEW.client_publish_status)
    );
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS project_condition_change_audit ON public.project_condition_records;
CREATE TRIGGER project_condition_change_audit AFTER INSERT OR UPDATE OF status, client_publish_status ON public.project_condition_records
FOR EACH ROW EXECUTE FUNCTION public.log_project_condition_change();

