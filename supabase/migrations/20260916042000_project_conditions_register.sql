-- Durable Project Conditions Register.
-- This is the client/reporting-grade register layer that can be sourced from
-- Field Accountability while preserving APAS/internal review from owner-visible
-- summaries.

CREATE TABLE IF NOT EXISTS public.project_condition_records (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id uuid NOT NULL REFERENCES public.workspaces(id) ON DELETE CASCADE,
  project_id uuid NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  field_item_id uuid REFERENCES public.field_accountability_items(id) ON DELETE SET NULL,
  condition_number bigint GENERATED BY DEFAULT AS IDENTITY,
  source_system text NOT NULL DEFAULT 'projos',
  source_record_id text,
  building_or_area text NOT NULL DEFAULT 'Project area' CHECK (length(trim(building_or_area)) BETWEEN 1 AND 180),
  elevation text,
  floor text,
  unit text,
  element text NOT NULL CHECK (length(trim(element)) BETWEEN 1 AND 240),
  location_label text,
  classification text NOT NULL DEFAULT 'needs_engineer_determination'
    CHECK (classification IN ('structural','non_structural','mixed','needs_engineer_determination')),
  classification_status text NOT NULL DEFAULT 'needs_review'
    CHECK (classification_status IN ('draft','needs_review','engineer_approved','returned')),
  observed_condition text NOT NULL CHECK (length(trim(observed_condition)) BETWEEN 1 AND 12000),
  condition_category text NOT NULL DEFAULT 'other' CHECK (length(trim(condition_category)) BETWEEN 1 AND 120),
  severity text NOT NULL DEFAULT 'to_be_determined'
    CHECK (severity IN ('low','moderate','high','critical','to_be_determined')),
  quantity numeric,
  quantity_unit text,
  repair_type text,
  spec_reference text,
  permit_status text NOT NULL DEFAULT 'not_determined'
    CHECK (permit_status IN ('not_determined','no_permit_expected','permit_required','held_pending_permit','permit_issued')),
  owner_signoff_status text NOT NULL DEFAULT 'not_ready'
    CHECK (owner_signoff_status IN ('not_ready','ready_for_owner','pending','approved','returned')),
  status text NOT NULL DEFAULT 'draft'
    CHECK (status IN ('draft','needs_apas_review','needs_engineer_review','ready_for_owner','held_pending_permit','released_for_contractor_pricing','in_construction','verified_complete','closed','void')),
  ai_suggestion text,
  ai_confidence numeric CHECK (ai_confidence IS NULL OR (ai_confidence >= 0 AND ai_confidence <= 1)),
  human_review_required boolean NOT NULL DEFAULT true,
  client_publish_status text NOT NULL DEFAULT 'internal_only'
    CHECK (client_publish_status IN ('internal_only','ready_to_publish','published_to_client','returned_before_publish')),
  client_summary text,
  created_by uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(project_id, source_system, source_record_id)
);

CREATE TABLE IF NOT EXISTS public.project_condition_comments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id uuid NOT NULL REFERENCES public.workspaces(id) ON DELETE CASCADE,
  project_id uuid NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  condition_id uuid NOT NULL REFERENCES public.project_condition_records(id) ON DELETE CASCADE,
  body text NOT NULL CHECK (length(trim(body)) BETWEEN 1 AND 10000),
  role text,
  audience text NOT NULL DEFAULT 'internal' CHECK (audience IN ('internal','client_visible')),
  created_by uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.project_condition_notations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id uuid NOT NULL REFERENCES public.workspaces(id) ON DELETE CASCADE,
  project_id uuid NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  condition_id uuid NOT NULL REFERENCES public.project_condition_records(id) ON DELETE CASCADE,
  notation_type text NOT NULL DEFAULT 'observed_condition' CHECK (length(trim(notation_type)) BETWEEN 1 AND 120),
  body text NOT NULL CHECK (length(trim(body)) BETWEEN 1 AND 10000),
  audience text NOT NULL DEFAULT 'internal' CHECK (audience IN ('internal','client_visible')),
  created_by uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.project_condition_photos (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id uuid NOT NULL REFERENCES public.workspaces(id) ON DELETE CASCADE,
  project_id uuid NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  condition_id uuid NOT NULL REFERENCES public.project_condition_records(id) ON DELETE CASCADE,
  field_photo_id uuid REFERENCES public.field_accountability_photos(id) ON DELETE SET NULL,
  photo_id uuid REFERENCES public.photos(id) ON DELETE SET NULL,
  evidence_type text NOT NULL DEFAULT 'observation'
    CHECK (evidence_type IN ('observation','before','progress','after','reference')),
  audience text NOT NULL DEFAULT 'internal' CHECK (audience IN ('internal','client_visible')),
  sort_order integer NOT NULL DEFAULT 0,
  created_by uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.project_condition_audit_events (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id uuid NOT NULL REFERENCES public.workspaces(id) ON DELETE CASCADE,
  project_id uuid NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  condition_id uuid NOT NULL REFERENCES public.project_condition_records(id) ON DELETE CASCADE,
  event_type text NOT NULL CHECK (length(trim(event_type)) BETWEEN 1 AND 120),
  note text,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  actor_id uuid DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS project_conditions_project_status_idx
