  ON public.project_condition_audit_events(condition_id, created_at);

CREATE OR REPLACE FUNCTION public.project_condition_set_updated_at()
RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS project_condition_records_updated_at ON public.project_condition_records;
CREATE TRIGGER project_condition_records_updated_at BEFORE UPDATE ON public.project_condition_records
FOR EACH ROW EXECUTE FUNCTION public.project_condition_set_updated_at();

CREATE OR REPLACE FUNCTION public.validate_project_condition_record()
RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
  IF NOT public.field_project_belongs_to_tenant(NEW.project_id, NEW.tenant_id) THEN
    RAISE EXCEPTION 'Project must belong to the same tenant';
  END IF;
  IF NEW.field_item_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.field_accountability_items item
    WHERE item.id = NEW.field_item_id
      AND item.tenant_id = NEW.tenant_id
      AND item.project_id = NEW.project_id
  ) THEN
    RAISE EXCEPTION 'Linked field accountability item must belong to the same tenant and project';
  END IF;
  IF NEW.client_publish_status IN ('ready_to_publish','published_to_client')
     AND length(trim(COALESCE(NEW.client_summary, ''))) < 1 THEN
    RAISE EXCEPTION 'Client-visible project conditions require a client summary';
  END IF;
  IF NEW.classification = 'needs_engineer_determination' AND NEW.classification_status = 'engineer_approved' THEN
    RAISE EXCEPTION 'Engineer approval requires a determined classification';
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.validate_project_condition_child()
RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM public.project_condition_records record
    WHERE record.id = NEW.condition_id
      AND record.tenant_id = NEW.tenant_id
      AND record.project_id = NEW.project_id
  ) THEN
    RAISE EXCEPTION 'Project condition child row must belong to the same condition, tenant, and project';
  END IF;
  IF TG_TABLE_NAME = 'project_condition_photos' AND NEW.field_photo_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.field_accountability_photos photo
    WHERE photo.id = NEW.field_photo_id
      AND photo.tenant_id = NEW.tenant_id
      AND photo.project_id = NEW.project_id
  ) THEN
    RAISE EXCEPTION 'Linked field photo must belong to the same tenant and project';
  END IF;
  IF TG_TABLE_NAME = 'project_condition_photos' AND NEW.photo_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.photos photo
    WHERE photo.id = NEW.photo_id
      AND photo.tenant_id = NEW.tenant_id
      AND photo.project_id = NEW.project_id
  ) THEN
    RAISE EXCEPTION 'Linked photo must belong to the same tenant and project';
  END IF;
  RETURN NEW;
END;
$$;

