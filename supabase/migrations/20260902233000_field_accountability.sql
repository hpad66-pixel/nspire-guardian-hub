CREATE OR REPLACE FUNCTION public.validate_field_accountability_linkage()
RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
DECLARE
  v_project uuid;
  v_tenant uuid;
BEGIN
  SELECT p.tenant_id, p.project_id INTO v_tenant, v_project
  FROM public.field_accountability_items p WHERE p.id = NEW.item_id;
  IF NEW.item_id IS NOT NULL AND (v_tenant IS DISTINCT FROM NEW.tenant_id OR v_project IS DISTINCT FROM NEW.project_id) THEN
    RAISE EXCEPTION 'Accountability item must belong to the same tenant and project';
  END IF;
  IF NEW.photo_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.photos ph WHERE ph.id = NEW.photo_id AND ph.tenant_id = NEW.tenant_id AND ph.project_id = NEW.project_id
  ) THEN
    RAISE EXCEPTION 'Photo must belong to the same tenant and project';
  END IF;
  IF TG_TABLE_NAME <> 'field_accountability_photos'
    AND NEW.item_id IS NOT NULL AND NEW.photo_id IS NOT NULL
    AND NOT EXISTS (
      SELECT 1 FROM public.field_accountability_photos fp
      WHERE fp.item_id = NEW.item_id AND fp.photo_id = NEW.photo_id
    ) THEN
    RAISE EXCEPTION 'Photo must be attached to this accountability item';
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.validate_field_accountability_item()
RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
  IF TG_OP = 'INSERT' AND NEW.status NOT IN ('needs_triage','assigned') THEN
    RAISE EXCEPTION 'New accountability items must begin in triage or assigned status';
  END IF;
  IF NOT public.field_project_belongs_to_tenant(NEW.project_id, NEW.tenant_id) THEN
    RAISE EXCEPTION 'Project must belong to the same tenant';
  END IF;
  IF NEW.visit_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.field_visits v
    WHERE v.id = NEW.visit_id AND v.tenant_id = NEW.tenant_id AND v.project_id = NEW.project_id
  ) THEN
    RAISE EXCEPTION 'Site walk must belong to the same tenant and project';
  END IF;
  IF NEW.property_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.properties p WHERE p.id = NEW.property_id AND p.workspace_id = NEW.tenant_id
  ) THEN
    RAISE EXCEPTION 'Property must belong to the same tenant';
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.validate_field_visit()
