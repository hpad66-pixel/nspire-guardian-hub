CREATE OR REPLACE FUNCTION public.log_field_accountability_status()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO public.field_accountability_events(tenant_id, project_id, item_id, action, to_status, actor_id)
    VALUES (NEW.tenant_id, NEW.project_id, NEW.id, 'created', NEW.status, NEW.created_by);
  ELSIF NEW.status IS DISTINCT FROM OLD.status THEN
    INSERT INTO public.field_accountability_events(tenant_id, project_id, item_id, action, from_status, to_status, actor_id)
    VALUES (NEW.tenant_id, NEW.project_id, NEW.id, 'status_changed', OLD.status, NEW.status, auth.uid());
  END IF;
  RETURN NEW;
END;
$$;

