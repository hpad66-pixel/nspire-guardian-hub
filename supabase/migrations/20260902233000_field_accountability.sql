CREATE OR REPLACE FUNCTION public.transition_field_accountability_item(
  p_item_id uuid,
  p_target_status text,
  p_note text DEFAULT NULL
) RETURNS public.field_accountability_items
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_item public.field_accountability_items;
  v_kind text := public.current_portal_kind();
  v_after_count integer;
BEGIN
  SELECT * INTO v_item FROM public.field_accountability_items WHERE id = p_item_id FOR UPDATE;
  IF v_item.id IS NULL THEN RAISE EXCEPTION 'Accountability item not found'; END IF;

  IF v_kind = 'owner' THEN
    IF NOT public.owner_can_access_project(v_item.project_id) OR NOT v_item.owner_visible THEN
      RAISE EXCEPTION 'Not authorized for this project';
    END IF;
    IF p_target_status NOT IN ('verified','reopened') THEN
      RAISE EXCEPTION 'Owners may only accept or reopen work';
    END IF;
    IF p_target_status = 'reopened' AND length(trim(COALESCE(p_note,''))) < 3 THEN
      RAISE EXCEPTION 'A reason is required to reopen work';
    END IF;
    IF p_target_status = 'verified' AND v_item.status <> 'ready_for_review' THEN
      RAISE EXCEPTION 'Only work ready for review can be accepted';
    END IF;
    IF p_target_status = 'reopened' AND v_item.status NOT IN ('ready_for_review','verified') THEN
      RAISE EXCEPTION 'Only submitted or verified work can be reopened';
    END IF;
  ELSIF v_kind <> 'main' AND NOT public.is_super_admin() THEN
    RAISE EXCEPTION 'Only project staff or an authorized owner may change status';
  ELSIF v_item.tenant_id <> public.current_tenant_id() AND NOT public.is_super_admin() THEN
    RAISE EXCEPTION 'Not authorized for this tenant';
  END IF;

  IF p_target_status NOT IN ('needs_triage','assigned','in_progress','ready_for_review','verified','reopened','deferred','rejected') THEN
    RAISE EXCEPTION 'Invalid target status';
  END IF;

  IF v_kind <> 'owner' AND NOT public.is_super_admin() AND NOT (
    (v_item.status = 'needs_triage' AND p_target_status IN ('assigned','deferred','rejected')) OR
    (v_item.status = 'assigned' AND p_target_status IN ('in_progress','deferred','rejected')) OR
    (v_item.status IN ('in_progress','reopened') AND p_target_status IN ('assigned','ready_for_review','deferred')) OR
    (v_item.status = 'ready_for_review' AND p_target_status IN ('verified','reopened')) OR
    (v_item.status = 'verified' AND p_target_status = 'reopened') OR
    (v_item.status IN ('deferred','rejected') AND p_target_status = 'assigned') OR
    v_item.status = p_target_status
  ) THEN
    RAISE EXCEPTION 'Invalid accountability status transition from % to %', v_item.status, p_target_status;
  END IF;

  IF p_target_status = 'ready_for_review' THEN
    SELECT count(*) INTO v_after_count FROM public.field_accountability_photos
    WHERE item_id = p_item_id AND evidence_type = 'after';
    IF v_after_count < 1 THEN RAISE EXCEPTION 'At least one after photo is required before review'; END IF;
  END IF;

  UPDATE public.field_accountability_items
  SET status = p_target_status,
      ready_for_review_at = CASE WHEN p_target_status = 'ready_for_review' THEN now() ELSE ready_for_review_at END,
      verified_at = CASE WHEN p_target_status = 'verified' THEN now() ELSE NULL END,
      verified_by = CASE WHEN p_target_status = 'verified' THEN auth.uid() ELSE NULL END,
      reopened_at = CASE WHEN p_target_status = 'reopened' THEN now() ELSE reopened_at END,
      ball_in_court = CASE
        WHEN p_target_status = 'ready_for_review' THEN 'apas'
        WHEN p_target_status = 'reopened' AND v_kind = 'owner' THEN 'property_management'
        ELSE ball_in_court END
  WHERE id = p_item_id RETURNING * INTO v_item;

  IF p_note IS NOT NULL AND trim(p_note) <> '' THEN
    INSERT INTO public.field_accountability_events(tenant_id, project_id, item_id, action, to_status, note, actor_id)
    VALUES (v_item.tenant_id, v_item.project_id, v_item.id, 'status_note', p_target_status, trim(p_note), auth.uid());
  END IF;
  RETURN v_item;
END;
$$;

