CREATE OR REPLACE FUNCTION public.field_project_belongs_to_tenant(p_project_id uuid, p_tenant_id uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.projects project
    LEFT JOIN public.properties property ON property.id = project.property_id
    LEFT JOIN public.clients client ON client.id = project.client_id
    LEFT JOIN public.profiles creator ON creator.user_id = project.created_by
    WHERE project.id = p_project_id
      AND p_tenant_id = COALESCE(property.workspace_id, client.workspace_id, creator.workspace_id)
  );
$$;

