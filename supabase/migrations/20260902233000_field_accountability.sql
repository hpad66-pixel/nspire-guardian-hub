CREATE POLICY project_photos_owner_accountability_read ON storage.objects FOR SELECT TO authenticated
USING (
  bucket_id = 'project-photos'
  AND public.current_portal_kind() = 'owner'
  AND EXISTS (
    SELECT 1
    FROM public.photos ph
    JOIN public.field_accountability_photos fp ON fp.photo_id = ph.id
    JOIN public.field_accountability_items i ON i.id = fp.item_id
    WHERE ph.storage_path = storage.objects.name
      AND i.owner_visible
      AND public.owner_can_access_project(i.project_id)
  )
);

