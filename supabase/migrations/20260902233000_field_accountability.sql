CREATE OR REPLACE FUNCTION public.enforce_field_after_photo_limit()
RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
  IF NEW.evidence_type = 'after' AND NEW.item_id IS NOT NULL AND (
    SELECT count(*) FROM public.field_accountability_photos fp
    WHERE fp.item_id = NEW.item_id AND fp.evidence_type = 'after' AND fp.id IS DISTINCT FROM NEW.id
  ) >= 3 THEN
    RAISE EXCEPTION 'A condition may have no more than three after photos';
  END IF;
  RETURN NEW;
END;
$$;

