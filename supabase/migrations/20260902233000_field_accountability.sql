-- One evidence-backed accountability spine for owner walks, inspections,
-- property-management rounds, maintenance work, and consultant observations.

CREATE TABLE IF NOT EXISTS public.field_visits (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id uuid NOT NULL REFERENCES public.workspaces(id) ON DELETE CASCADE,
  project_id uuid NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  property_id uuid REFERENCES public.properties(id) ON DELETE SET NULL,
  title text NOT NULL CHECK (length(trim(title)) BETWEEN 1 AND 180),
  visit_type text NOT NULL DEFAULT 'property_manager_walk'
    CHECK (visit_type IN ('owner_walk','apas_inspection','property_manager_walk','maintenance_walk','crew_update','other')),
  visited_at timestamptz NOT NULL DEFAULT now(),
  status text NOT NULL DEFAULT 'triage' CHECK (status IN ('draft','triage','active','complete')),
  notes text,
  created_by uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.field_accountability_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id uuid NOT NULL REFERENCES public.workspaces(id) ON DELETE CASCADE,
  project_id uuid NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  property_id uuid REFERENCES public.properties(id) ON DELETE SET NULL,
  visit_id uuid REFERENCES public.field_visits(id) ON DELETE SET NULL,
  item_number bigint GENERATED BY DEFAULT AS IDENTITY,
  title text NOT NULL CHECK (length(trim(title)) BETWEEN 1 AND 180),
  description text,
  category text NOT NULL DEFAULT 'other'
    CHECK (category IN ('life_safety','water_intrusion','building_envelope','grounds','cleanliness','electrical','plumbing','hvac','structural','accessibility','security','other')),
  severity text NOT NULL DEFAULT 'medium' CHECK (severity IN ('low','medium','high','critical')),
  location_label text,
  lat numeric,
  lng numeric,
  status text NOT NULL DEFAULT 'needs_triage'
    CHECK (status IN ('needs_triage','assigned','in_progress','ready_for_review','verified','reopened','deferred','rejected')),
  ball_in_court text NOT NULL DEFAULT 'property_management'
    CHECK (ball_in_court IN ('apas','property_management','maintenance','owner','vendor')),
  responsible_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  responsible_contact_id uuid,
  responsible_organization_id uuid REFERENCES public.organizations(id) ON DELETE SET NULL,
  work_order_id uuid REFERENCES public.work_orders(id) ON DELETE SET NULL,
  source_type text,
  source_record_id uuid,
  due_date date,
  repeat_count integer NOT NULL DEFAULT 0 CHECK (repeat_count >= 0),
  owner_visible boolean NOT NULL DEFAULT true,
  owner_verification_required boolean NOT NULL DEFAULT false,
  ready_for_review_at timestamptz,
  verified_at timestamptz,
  verified_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  reopened_at timestamptz,
  archived_at timestamptz,
  created_by uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
